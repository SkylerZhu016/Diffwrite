test('AI suggestions are separate; a newer human edit is never overwritten',t=>{
  const s=setup(t);
  const input={requestId:'incoming',title:'测试稿',text:'原句。下一句。',format:'plain'};
  const meta=s.publish(input);
  assert.equal(s.publish(input).id,meta.id);
  assert.throws(()=>s.publish({...input,text:'另一篇。'}),/不同内容/);
  assert.equal(meta.aiReview,false);
  assert.equal(meta.humanReview,false);
  const one={requestId:'review',draftId:meta.id,expectedRevision:1,
    suggestions:[{sentence:0,original:'原句。',opinion:'AI 看法',replacement:'建议。'}]};
  const recipient=s.createConnection("审稿 AI");
  const review=s.review(one,recipient);
  assert.deepEqual(s.review(one,recipient),review);
  let record=s.read(meta.id);
  assert.equal(record.meta.aiReview,true);
  assert.equal(s.readSentences(meta.id,0,1).sentences[0].effective,'原句。');
  record.draft.notes[0]={opinion:'人工意见',revision:'人工改动。'};
  const saved=s.saveBrowser(record.meta,record.draft);
  assert.equal(saved.humanReview,true);
  assert.throws(()=>s.decide(meta.id,review.suggestionIds[0],'accept',saved.revision),/未覆盖/);
  const next=s.review({...one,requestId:'review-new',expectedRevision:saved.revision},recipient);
  record=s.decide(meta.id,next.suggestionIds[0],'accept',saved.revision);
  assert.deepEqual(record.draft.notes[0],{opinion:'人工意见',revision:'建议。'});
  const n=s.notify(meta.id,record.meta.revision,recipient);
  const changes=s.readNotice(n.id,0,30,recipient).changes;
  assert.equal(changes[0].opinion,'人工意见');
  assert.equal(changes[0].decisions[0].state,'accepted');
  s.ack(n.id,recipient);
  assert.deepEqual(s.listNotices(30,recipient),[]);
  assert.equal(s.notify(meta.id,record.meta.revision,recipient).changeCount,0);
});
